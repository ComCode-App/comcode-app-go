export interface ParamDefinition {
  name: string;
  type: "number" | "string" | "string[]" | "enum" | "boolean";
  labelTr: string;
  labelEn: string;
  min?: number;
  max?: number;
  step?: number;
  options?: string[];
  isColor?: boolean;
  defaultValue?: unknown;
  category?: "custom" | "sizing" | "motion" | "color";
}

export interface ShaderRegistryItem {
  id: string;
  name: string;
  nameTr: string;
  descriptionTr: string;
  descriptionEn: string;
  category: "effects" | "patterns" | "noise" | "imageFilters" | "logo";
  // Heterogeneous registry: each shader component has its own props type.
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  component: FC<any>;
  presets: Array<{ name: string; params: Record<string, unknown> }>;
  defaultParams: Record<string, unknown>;
  params: ParamDefinition[];
  supportsImage?: boolean;
}

