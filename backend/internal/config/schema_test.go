package config

import (
	"bufio"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"testing"
)

// The schema lives outside the Go module (go:embed cannot reach it), so the
// tests read it from the repository checkout.
var schemaPath = filepath.Join("..", "..", "..", "deploy", "env", "schema")

// Schema secrets the backend guard does not cover, and why.
var unguardedSchemaSecrets = map[string]string{
	"AUTH_SECRET":       "read by the Next.js frontend only",
	"VAPID_PUBLIC_KEY":  "public by design",
	"VAPID_PRIVATE_KEY": "no development default; empty turns Web Push off",
}

// schemaSecret is a generated key of deploy/env/schema: `secret:<kind>:<n>`
// or one half of the `vapid:` pair (Kind "vapid", N 0).
type schemaSecret struct {
	Kind string
	N    int
}

// schemaSecrets parses every `secret:` and `vapid:` key of the schema.
func schemaSecrets(t *testing.T) map[string]schemaSecret {
	t.Helper()
	f, err := os.Open(schemaPath)
	if err != nil {
		t.Fatalf("open schema: %v", err)
	}
	defer func() { _ = f.Close() }()
	secret := regexp.MustCompile(`^([A-Z][A-Z0-9_]*)\s*\|\s*secret:(hex|b64|alnum):([0-9]+)\s*$`)
	vapid := regexp.MustCompile(`^([A-Z][A-Z0-9_]*)\s*\|\s*vapid:`)
	out := map[string]schemaSecret{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if m := secret.FindStringSubmatch(sc.Text()); m != nil {
			n, _ := strconv.Atoi(m[3])
			out[m[1]] = schemaSecret{Kind: m[2], N: n}
		} else if m := vapid.FindStringSubmatch(sc.Text()); m != nil {
			out[m[1]] = schemaSecret{Kind: "vapid"}
		}
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}
	if len(out) == 0 {
		t.Fatal("no secret: keys parsed from the schema")
	}
	return out
}

// generatedLen is the length of the value scripts/prod-env.sh generates.
func (s schemaSecret) generatedLen() int {
	switch s.Kind {
	case "hex":
		return 2 * s.N
	case "b64":
		return 4 * ((s.N + 2) / 3)
	default:
		return s.N
	}
}

// A secret added to deploy/env/schema must be guarded (or exempted with a
// reason), and the guard must not cover keys the schema no longer generates.
func TestGuardedSecretsMatchSchema(t *testing.T) {
	schema := schemaSecrets(t)
	guarded := map[string]bool{}
	for _, s := range guardedSecrets {
		guarded[s.Key] = true
	}
	for key, why := range unguardedSchemaSecrets {
		if guarded[key] {
			t.Errorf("%s is both guarded and exempted (%s)", key, why)
		}
		if _, ok := schema[key]; !ok {
			t.Errorf("unguardedSchemaSecrets has %s (%s) but the schema no longer generates it", key, why)
		}
	}
	keys := make([]string, 0, len(schema))
	for key := range schema {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		if !guarded[key] && unguardedSchemaSecrets[key] == "" {
			t.Errorf("schema secret %s has no entry in guardedSecrets (guard.go); add one or exempt it with a reason", key)
		}
	}
	for _, s := range guardedSecrets {
		if _, ok := schema[s.Key]; !ok {
			t.Errorf("guardedSecrets guards %s, which is not a secret: key in %s", s.Key, schemaPath)
		}
	}
}

// A value generated by scripts/prod-env.sh init must pass the guard: it is
// never shorter than the guard's minimum.
func TestSchemaSecretsMeetGuardMinimum(t *testing.T) {
	schema := schemaSecrets(t)
	for _, s := range guardedSecrets {
		sec, ok := schema[s.Key]
		if !ok || sec.Kind == "vapid" {
			continue // reported by TestGuardedSecretsMatchSchema
		}
		if got := sec.generatedLen(); got < s.MinLen {
			t.Errorf("schema generates %s with %d characters, below the guard minimum %d", s.Key, got, s.MinLen)
		}
	}
}
